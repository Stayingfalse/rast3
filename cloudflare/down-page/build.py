#!/usr/bin/env python3
"""Build the self-contained down page into src/page.generated.js.

The origin is offline whenever this page is shown, so everything it needs is
inlined: Archivo (subset to the characters on the page, as woff2), the brand
stamp and the hanging-post sky from public/brand.

    pip install fonttools brotli
    python3 cloudflare/down-page/build.py
"""
import base64
import io
import json
import pathlib
import re

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PUBLIC = ROOT / "public"

# Printable ASCII plus the typographic marks the copy uses.
CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + "’‘“”–—…·"


def woff2(name: str) -> str:
    font = TTFont(PUBLIC / "fonts" / name)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern", "liga", "tnum", "lnum"]
    sub = subset.Subsetter(opts)
    sub.populate(text=CHARS)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return base64.b64encode(buf.getvalue()).decode()


def svg(name: str) -> str:
    text = (PUBLIC / "brand" / name).read_text()
    text = re.sub(r"<\?xml[^>]*>\s*", "", text)
    # Give each inlined SVG its own ids so masks don't collide.
    prefix = name.split(".")[0].replace("-", "")
    text = re.sub(r'id="([^"]+)"', lambda m: f'id="{prefix}{m.group(1)}"', text)
    text = re.sub(r"url\(#([^)]+)\)", lambda m: f"url(#{prefix}{m.group(1)})", text)
    text = re.sub(r'href="#([^"]+)"', lambda m: f'href="#{prefix}{m.group(1)}"', text)
    return text.strip()


page = (HERE / "src" / "page.html").read_text()
stamp_raw = (PUBLIC / "brand" / "stamp.svg").read_bytes()
values = {
    "FONT_400": woff2("archivo-400.ttf"),
    "FONT_600": woff2("archivo-600.ttf"),
    "FONT_X800": woff2("archivo-expanded-800.ttf"),
    "STAMP": svg("stamp.svg"),
    "STAMP_B64": base64.b64encode(stamp_raw).decode(),
    "SKY_LEFT": svg("sky-left.svg"),
    "SKY_RIGHT": svg("sky-right.svg"),
}
for key, value in values.items():
    page = page.replace("{{" + key + "}}", value)

left = sorted(set(re.findall(r"\{\{([A-Z_0-9]+)\}\}", page)) - {"YEAR"})
if left:
    raise SystemExit(f"unfilled placeholders: {left}")

out = HERE / "src" / "page.generated.js"
out.write_text(
    "// Generated by cloudflare/down-page/build.py from src/page.html. Do not edit.\n"
    f"const page = {json.dumps(page, ensure_ascii=False)};\nexport default page;\n"
)
print(f"wrote {out.relative_to(ROOT)} ({len(page.encode()) // 1024} KB)")
