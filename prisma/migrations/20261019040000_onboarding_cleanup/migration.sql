-- 1. Re-date memberships created by the Day 8 backfill (ids "m_…"). They were
--    dated from profile completion, or the backfill time when that was
--    missing, so long-standing members showed as recent joiners. Use the
--    person's earliest activity instead, else the start of the 2025 season.
UPDATE `Membership` m
JOIN (
  SELECT u.`id` AS userId,
         NULLIF(LEAST(
           COALESCE((SELECT MIN(a.`assignedAt`) FROM `WishlistAssignment` a WHERE a.`assignedUserId` = u.`id` OR a.`wishlistOwnerId` = u.`id`), '9999-12-31 00:00:00.000'),
           COALESCE((SELECT MIN(p.`purchasedAt`) FROM `Purchase` p WHERE p.`userId` = u.`id`), '9999-12-31 00:00:00.000'),
           COALESCE((SELECT MIN(k.`createdAt`) FROM `Kudos` k WHERE k.`userId` = u.`id`), '9999-12-31 00:00:00.000'),
           COALESCE(u.`profileCompletedAt`, '9999-12-31 00:00:00.000')
         ), '9999-12-31 00:00:00.000') AS firstSeen
  FROM `User` u
) f ON f.userId = m.`userId`
SET m.`joinedAt` = COALESCE(f.firstSeen, '2025-11-01 00:00:00.000')
WHERE m.`id` LIKE 'm\_%';

